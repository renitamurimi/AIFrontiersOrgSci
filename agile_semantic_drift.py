# 2. Helper function to load text

def load_corpus_from_file(filename):
    """Safely loads text lines from a local file, ignoring empty lines."""
    if not os.path.exists(filename):
        print(f"[Warning] '{filename}' not found. Creating a placeholder file.")
        with open(filename, 'w', encoding='utf-8') as f:
            f.write("Placeholder text line for testing the pipeline.\n")

    with open(filename, 'r', encoding='utf-8') as f:
        corpus = [line.strip() for line in f if line.strip()]
    return corpus

def compute_vector_metrics(vec1: np.ndarray, vec2: np.ndarray) -> tuple[float, float]:
    """Calculates Cosine Similarity and Drift (1 - Similarity) between two 2D vectors."""
    similarity = float(cosine_similarity(vec1, vec2)[0][0])
    drift = 1.0 - similarity
    return similarity, drift


def run_pilot_study(
    early_path: str = '/content/drive/MyDrive/ms/insider_early.txt',
    mature_path: str = '/content/drive/MyDrive/ms/insider_mature.txt',
    trans_path: str = '/content/drive/MyDrive/ms/outsider_translation.txt',
    model: SentenceTransformer = None
):
    print("=" * 50)
    print("  EPISTEMIC LIFECYCLE & ROSETTA STONE PILOT TOOL  ")
    print("=" * 50 + "\n")

    # 1. Load Corpora
    early_corpus = load_corpus_from_file(early_path)
    mature_corpus = load_corpus_from_file(mature_path)
    translation_corpus = load_corpus_from_file(trans_path)

    print(f"Loaded: {len(early_corpus)} early, {len(mature_corpus)} mature, {len(translation_corpus)} translation texts.\n")

    if not (early_corpus and mature_corpus and translation_corpus):
        print("[Error] One or more corpora are empty. Please check your files.")
        return

    # --- PIPELINE 1: TF-IDF (Lexical Space) ---
    print("Calculating TF-IDF Lexical Metrics...")
    vectorizer = TfidfVectorizer(stop_words='english')
    all_texts = early_corpus + mature_corpus + translation_corpus
    vectorizer.fit(all_texts)

    vocab = vectorizer.get_feature_names_out()
    print(f"Total unique conceptual tokens: {len(vocab)}")
    print(f"Sample vocabulary signature: {list(vocab)[:6]}...\n")

    # Aggregate & normalize sparse TF-IDF vectors
    early_vec_tfidf = normalize(np.asarray(vectorizer.transform(early_corpus).mean(axis=0)).reshape(1, -1))
    mature_vec_tfidf = normalize(np.asarray(vectorizer.transform(mature_corpus).mean(axis=0)).reshape(1, -1))
    trans_vec_tfidf = normalize(np.asarray(vectorizer.transform(translation_corpus).mean(axis=0)).reshape(1, -1))

    # Metrics
    sim_tfidf, drift_tfidf = compute_vector_metrics(early_vec_tfidf, mature_vec_tfidf)
    bound_tfidf, gap_tfidf = compute_vector_metrics(mature_vec_tfidf, trans_vec_tfidf)

    # --- PIPELINE 2: S-BERT (Deep Semantic Space) ---
    if model is None:
        print("Loading dense semantic model (Sentence-BERT)...")
        model = SentenceTransformer('all-MiniLM-L6-v2')

    print("Encoding corpora into dense vector spaces...")
    # Setting normalize_embeddings=True standardizes dense vectors upon generation
    early_dense = model.encode(early_corpus, show_progress_bar=False, normalize_embeddings=True)
    mature_dense = model.encode(mature_corpus, show_progress_bar=False, normalize_embeddings=True)
    trans_dense = model.encode(translation_corpus, show_progress_bar=False, normalize_embeddings=True)

    # Mean pooling across documents + re-normalizing centroid vectors to unit length
    early_vec_dense = normalize(early_dense.mean(axis=0).reshape(1, -1))
    mature_vec_dense = normalize(mature_dense.mean(axis=0).reshape(1, -1))
    trans_vec_dense = normalize(trans_dense.mean(axis=0).reshape(1, -1))

    # Metrics
    sim_dense, drift_dense = compute_vector_metrics(early_vec_dense, mature_vec_dense)
    bound_dense, gap_dense = compute_vector_metrics(mature_vec_dense, trans_vec_dense)

    # --- HYBRID COMPARATIVE OUTPUT REPORT ---
    print("\n" + "=" * 50)
    print("        HYBRID ACADEMIC METRIC COMPARISON          ")
    print("=" * 50)
    print(f"{'Metric / Index':<30} | {'TF-IDF (Lexical)':<18} | {'S-BERT (Dense)':<18}")
    print("-" * 73)
    print(f"{'Internal Similarity':<30} | {sim_tfidf:<18.4f} | {sim_dense:<18.4f}")
    print(f"{'Semantic Drift Index':<30} | {drift_tfidf:<18.4f} | {drift_dense:<18.4f}")
    print("-" * 73)
    print(f"{'External Alignment':<30} | {bound_tfidf:<18.4f} | {bound_dense:<18.4f}")
    print(f"{'Translation Friction Gap':<30} | {gap_tfidf:<18.4f} | {gap_dense:<18.4f}")
    print("=" * 50)

    # Interpretations
    print("\n--- Pilot Interpretations ---")
    if drift_tfidf > 0.4:
        print("-> [TF-IDF] High lexical drift: Terminology changed significantly over time.")
    else:
        print("-> [TF-IDF] Low lexical drift: Vocabulary remained consistent.")

    if drift_dense > 0.4:
        print("-> [S-BERT] High conceptual shift: Core meaning shifted significantly.")
    else:
        print("-> [S-BERT] Low conceptual shift: Core meaning remained stable.")

    if gap_tfidf > 0.5:
        print("-> [TF-IDF] High translation friction: Missing technical vocabulary in translation layer.")

    if gap_dense > 0.5:
        print("-> [S-BERT] High semantic gap: Conceptual intent is altered in translation layer.")

    print("\n" + "=" * 50)
    print("  PILOT STUDY EXECUTION COMPLETE                  ")
    print("=" * 50)

# 4. Run the entire pipeline
if __name__ == "__main__":
    run_pilot_study()
